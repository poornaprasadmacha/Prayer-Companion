/**
 * Returns deterministic daily content based on the provided date (defaults to today).
 * Index is based on day of month (1-31), ensuring stability throughout the day.
 * @param {Date|string} [targetDate]
 * @returns {{verse: {text: string, reference: string, translation: string}, quote: {text: string, author: string}, day: number}}
 */
function getDailyContent(targetDate = new Date()) {
  const d = targetDate instanceof Date ? targetDate : new Date(targetDate);
  const dayOfMonth = d.getDate(); // 1 to 31
  const index = Math.max(0, Math.min(DAILY_CONTENT.length - 1, dayOfMonth - 1));
  return DAILY_CONTENT[index] || DAILY_CONTENT[0];
}

